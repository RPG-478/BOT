-- RTA data is used only by the server-side bot client. RLS is intentionally disabled per project convention.
CREATE TABLE IF NOT EXISTS public.bump_rta_settings (
    guild_id text PRIMARY KEY,
    channel_id text NOT NULL,
    disboard_bot_id text NOT NULL,
    disoku_bot_id text NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.bump_rta_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id text NOT NULL,
    user_id text NOT NULL,
    elapsed_ms integer NOT NULL CHECK (elapsed_ms > 0),
    bump_message_id text,
    completed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS bump_rta_events_guild_time_idx
    ON public.bump_rta_events (guild_id, completed_at DESC);
CREATE INDEX IF NOT EXISTS bump_rta_events_user_time_idx
    ON public.bump_rta_events (user_id, elapsed_ms ASC);
CREATE TABLE IF NOT EXISTS public.bump_rta_records (
    guild_id text NOT NULL,
    user_id text NOT NULL,
    elapsed_ms integer NOT NULL CHECK (elapsed_ms > 0),
    completed_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (guild_id, user_id)
);
CREATE INDEX IF NOT EXISTS bump_rta_records_ranking_idx
    ON public.bump_rta_records (guild_id, elapsed_ms ASC);
CREATE TABLE IF NOT EXISTS public.bump_rta_reminders (
    message_id text PRIMARY KEY,
    guild_id text NOT NULL,
    channel_id text NOT NULL,
    user_id text,
    event_type text NOT NULL CHECK (event_type IN ('bump', 'up')),
    due_at timestamptz NOT NULL,
    sent_at timestamptz
);
CREATE INDEX IF NOT EXISTS bump_rta_reminders_due_idx
    ON public.bump_rta_reminders (due_at) WHERE sent_at IS NULL;

-- RLS is deliberately disabled for the RTA tables.
ALTER TABLE public.bump_rta_settings DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.bump_rta_events DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.bump_rta_records DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.bump_rta_reminders DISABLE ROW LEVEL SECURITY;

-- A slower concurrent result never overwrites the current personal best.
CREATE OR REPLACE FUNCTION public.record_bump_rta_best(
    p_guild_id text, p_user_id text, p_elapsed_ms integer, p_completed_at timestamptz
) RETURNS void
LANGUAGE sql
SECURITY INVOKER
AS $$
    INSERT INTO public.bump_rta_records (guild_id, user_id, elapsed_ms, completed_at)
    VALUES (p_guild_id, p_user_id, p_elapsed_ms, p_completed_at)
    ON CONFLICT (guild_id, user_id) DO UPDATE
      SET elapsed_ms = EXCLUDED.elapsed_ms, completed_at = EXCLUDED.completed_at
      WHERE EXCLUDED.elapsed_ms < public.bump_rta_records.elapsed_ms;
$$;
REVOKE ALL ON FUNCTION public.record_bump_rta_best(text, text, integer, timestamptz) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.record_bump_rta_best(text, text, integer, timestamptz) TO service_role;

-- Cross-server leaderboard aggregates every completed run by Discord user.
CREATE OR REPLACE FUNCTION public.get_bump_rta_global_ranking(p_limit integer DEFAULT 10)
RETURNS TABLE(user_id text, elapsed_ms integer, attempts bigint)
LANGUAGE sql
SECURITY INVOKER
AS $$
    SELECT e.user_id, min(e.elapsed_ms)::integer AS elapsed_ms, count(*)::bigint AS attempts
    FROM public.bump_rta_events AS e
    GROUP BY e.user_id
    ORDER BY min(e.elapsed_ms) ASC
    LIMIT greatest(1, least(coalesce(p_limit, 10), 100));
$$;
REVOKE ALL ON FUNCTION public.get_bump_rta_global_ranking(integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_bump_rta_global_ranking(integer) TO service_role;
