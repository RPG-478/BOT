-- 個人プレイリスト機能用のSupabase/PostgreSQLスキーマ
-- BotはSUPABASE_KEY（公開キー）で接続し、RLSで操作範囲を制御します。

create table if not exists public.user_music_playlists (
    id bigint generated by default as identity primary key,
    guild_id bigint not null,
    owner_user_id bigint not null,
    name text not null check (char_length(name) between 1 and 100),
    tracks jsonb not null default '[]'::jsonb check (jsonb_typeof(tracks) = 'array'),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint user_music_playlists_owner_name_unique unique (guild_id, owner_user_id, name)
);

create index if not exists user_music_playlists_owner_lookup_idx
    on public.user_music_playlists (guild_id, owner_user_id, updated_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists user_music_playlists_set_updated_at on public.user_music_playlists;
create trigger user_music_playlists_set_updated_at
before update on public.user_music_playlists
for each row execute function public.set_updated_at();

